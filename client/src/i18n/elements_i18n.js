export function getLocalizedElement(element, lang = 'en') {
  if (!element) return null;
  const num = element.number;
  const nameMap = ELEMENT_NAMES_I18N[num];
  const localizedName = (nameMap && nameMap[lang]) || element.name;
  const catMap = CATEGORIES_I18N[element.category];
  const localizedCategory = (catMap && catMap[lang]) || element.category;
  const affMap = AFFINITIES_I18N[element.affinity];
  const localizedAffinity = (affMap && affMap[lang]) || { name: element.affinity, desc: '' };

  return {
    ...element,
    displayName: localizedName,
    displayCategory: localizedCategory,
    displayAffinityName: localizedAffinity.name,
    displayAffinityDesc: localizedAffinity.desc,
  };
}
